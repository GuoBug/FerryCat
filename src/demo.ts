/**
 * FerryCat Zero-Config Sandbox Demo (REQ-EXP-01).
 *
 * Runs a complete contract lifecycle — dispatch -> claim -> supervised execution -> TOCTOU
 * re-verification -> COMPLETED — entirely inside an isolated temporary sandbox, so a brand-new
 * user can see the deterministic handoff loop without configuring a single MCP server.
 *
 * Design constraints:
 *  - Zero pollution: every artifact (sample source, handler script, SQLite database) lives under
 *    `os.tmpdir()/ferrycat-demo-*`. The user's real workspace and `~/.ferrycat/mesh.db` are never touched.
 *  - No simulation shortcuts on the engine path: the demo drives the exact same public APIs a real
 *    daemon uses (`dispatchContract` / `pollNextTask` / `executeTaskAndFulfill` / `verifyContract`),
 *    so a green demo is genuine evidence rather than a puppet show.
 *  - Machine-readable mode: with `json: true` the function writes nothing to stdout and returns a
 *    plain object, keeping CI/upstream automation parseable.
 */
import fs from 'node:fs';
import os from 'node:os';
import path from 'node:path';
import { FerryCatEngine } from './engine.js';
import { executeTaskAndFulfill, type ContractPayload } from './supervisor.js';

const TOTAL_STEPS = 4;

const SAMPLE_REL_PATH = 'src/calc.ts';

/**
 * Sample source under review. Deliberately contains exactly one advisory-level defect
 * (`==` instead of `===`) so the demo handler has something real to find and the verdict
 * is deterministic across runs and platforms.
 */
const SAMPLE_SOURCE = `export function add(a: number, b: number): number {
  return a + b;
}

export function divide(a: number, b: number): number {
  if (b == 0) {
    throw new Error('Division by zero');
  }
  return a / b;
}

export const VERSION = '1.0.0';
`;

/**
 * Handler script written into the sandbox. It reads the contract from stdin (same protocol as
 * scripts/review-handler.js), inspects the real pointer file on disk, then emits a delivery
 * envelope on stdout. `execDelayMs` keeps the child alive long enough for the supervisor
 * heartbeat ticker to fire at least once, so the demo can prove lease renewal is live.
 */
function buildHandlerScript(execDelayMs: number): string {
  return `/**
 * FerryCat demo handler (generated by \`ferrycat-cli demo\`).
 * Reads the contract JSON from stdin, inspects the pointer file, prints a delivery envelope.
 */
const fs = require('node:fs');
const path = require('node:path');

const EXEC_DELAY_MS = ${execDelayMs};

function inspect(workspaceRoot, pointers) {
  const issues = [];
  for (const pointer of pointers || []) {
    const absPath = path.resolve(workspaceRoot, pointer.path);
    if (!fs.existsSync(absPath)) {
      issues.push(pointer.path + ': file is missing on disk');
      continue;
    }
    const lines = fs.readFileSync(absPath, 'utf8').split(/\\r?\\n/);
    lines.forEach((line, idx) => {
      // Loose equality on a numeric/string guard is the classic review catch.
      if (/(^|[^=!<>])==([^=]|$)/.test(line)) {
        issues.push(pointer.path + ':' + (idx + 1) + " uses '==' instead of '===' (strict equality)");
      }
    });
  }
  return issues;
}

function main() {
  const raw = fs.readFileSync(0, 'utf8');
  if (!raw.trim()) {
    console.error('demo handler: no contract payload received on stdin');
    process.exit(1);
  }
  const contract = JSON.parse(raw);
  const workspaceRoot = process.env.FERRYCAT_WORKSPACE_ROOT || process.cwd();
  const issues = inspect(workspaceRoot, contract.pointers);

  const finish = () => {
    process.stdout.write(
      JSON.stringify({
        ok: true,
        summary:
          'Reviewed ' + (contract.pointers || []).length + ' file(s) for contract ' +
          contract.contract_id + '; ' + issues.length + ' advisory finding(s).',
        structured_output: {
          passed: true,
          issues,
        },
      }) + '\\n'
    );
  };

  if (EXEC_DELAY_MS > 0) {
    setTimeout(finish, EXEC_DELAY_MS);
  } else {
    finish();
  }
}

main();
`;
}

export interface DemoOptions {
  /** Keep the sandbox directory on disk and report its path instead of deleting it. */
  keep?: boolean;
  /** Suppress all human-readable output; the caller receives only the structured result. */
  json?: boolean;
  /** Sink for human-readable lines. Defaults to process.stdout. Ignored when `json` is true. */
  write?: (line: string) => void;
  /** Force ANSI colors on/off. Defaults to auto-detection (TTY and no NO_COLOR). */
  color?: boolean;
  /** Lifetime of the demo child process in ms (0 = finish immediately). */
  execDelayMs?: number;
  /** Execution TTL granted to the demo contract, in seconds. */
  execTtlSec?: number;
}

export interface DemoStepRecord {
  index: number;
  total: number;
  title: string;
  fields: Record<string, string>;
}

export interface DemoResult {
  ok: boolean;
  sandbox: string;
  sandbox_kept: boolean;
  contract_id: string;
  claim_token: string;
  status: string;
  verdict: 'PASSED' | 'CHANGES_REQUESTED';
  issues: string[];
  dirty_files: number;
  heartbeat_renewals: number;
  elapsed_ms: number;
  steps: DemoStepRecord[];
  warnings: string[];
}

function makePainter(enabled: boolean) {
  const wrap = (code: string) => (text: string) =>
    enabled ? `\u001b[${code}m${text}\u001b[0m` : text;
  return {
    bold: wrap('1'),
    dim: wrap('2'),
    green: wrap('32'),
    cyan: wrap('36'),
    yellow: wrap('33'),
    magenta: wrap('35'),
    gray: wrap('90'),
    red: wrap('31'),
  };
}

function shortSha(sha: string): string {
  return sha.length <= 12 ? sha : `${sha.slice(0, 8)}...${sha.slice(-4)}`;
}

function removeSandbox(sandbox: string): void {
  // Windows keeps WAL/SHM handles briefly after close(); retries absorb that window.
  fs.rmSync(sandbox, { recursive: true, force: true, maxRetries: 5, retryDelay: 50 });
}

export async function runDemo(options: DemoOptions = {}): Promise<DemoResult> {
  const startedAt = Date.now();
  const execDelayMs = Math.max(0, options.execDelayMs ?? 1900);
  const execTtlSec = Math.max(2, options.execTtlSec ?? 5);
  const human = !options.json;
  const colorOn =
    options.color ?? (human && Boolean(process.stdout.isTTY) && !process.env.NO_COLOR);
  const paint = makePainter(colorOn);
  const write = options.write ?? ((line: string) => process.stdout.write(`${line}\n`));
  const say = (line = '') => {
    if (human) write(line);
  };

  const sandbox = fs.mkdtempSync(path.join(os.tmpdir(), 'ferrycat-demo-'));
  let engine: FerryCatEngine | undefined;
  let succeeded = false;

  const steps: DemoStepRecord[] = [];
  const warnings: string[] = [];
  let heartbeatRenewals = 0;
  let contractId = '';
  let claimToken = '';
  let status = 'UNKNOWN';
  let verdict: 'PASSED' | 'CHANGES_REQUESTED' = 'PASSED';
  let issues: string[] = [];
  let dirtyFiles = 0;

  const record = (index: number, title: string, fields: Record<string, string>) => {
    steps.push({ index, total: TOTAL_STEPS, title, fields });
    say('');
    say(`  ${paint.green('✔')} ${paint.bold(`[${index}/${TOTAL_STEPS}] ${title}`)}`);
    for (const [key, value] of Object.entries(fields)) {
      say(`    ${paint.gray(key.padEnd(10))}${value}`);
    }
  };

  try {
    // ---------------------------------------------------------------------
    // Sandbox scaffolding (isolated workspace + handler + SQLite database)
    // ---------------------------------------------------------------------
    const srcDir = path.join(sandbox, 'src');
    fs.mkdirSync(srcDir, { recursive: true });
    fs.writeFileSync(path.join(sandbox, SAMPLE_REL_PATH), SAMPLE_SOURCE, 'utf8');
    const handlerPath = path.join(sandbox, 'demo-handler.cjs');
    fs.writeFileSync(handlerPath, buildHandlerScript(execDelayMs), 'utf8');

    engine = new FerryCatEngine({ dbPath: path.join(sandbox, 'demo-mesh.db') });

    say('');
    say(paint.bold('⚡ FerryCat Zero-Config Sandbox Demo ⚡'));
    say(`${paint.gray('Sandbox:')} ${sandbox}`);
    say(paint.gray('No MCP config. No daemon. Your real workspace and mesh.db are untouched.'));

    // ---------------------------------------------------------------------
    // [1/4] Dispatch — Antigravity locks the pointer fingerprint
    // ---------------------------------------------------------------------
    const dispatchRes = engine.dispatchContract({
      requester_agent: 'antigravity',
      target_agent: 'workbuddy',
      task_type: 'code_review',
      title: 'Review calc.ts for correctness and strict-equality hygiene',
      context_summary:
        'Sandbox demo contract. Inspect src/calc.ts and report any correctness or ' +
        'strict-equality violations. This contract is generated by `ferrycat-cli demo`.',
      workspace_root: sandbox,
      pointers: [{ path: SAMPLE_REL_PATH }],
      contract_schema: {
        type: 'object',
        properties: {
          passed: { type: 'boolean' },
          issues: { type: 'array', items: { type: 'string' } },
        },
        required: ['passed', 'issues'],
        additionalProperties: false,
      },
      exec_ttl_sec: execTtlSec,
    });
    contractId = dispatchRes.contract_id;
    const lockedFile = dispatchRes.files[0];
    if (dispatchRes.warning) {
      warnings.push(dispatchRes.warning);
    }

    record(1, 'Contract Dispatched', {
      ID: contractId,
      Actor: `antigravity -> workbuddy ${paint.dim('(task: code_review)')}`,
      Locked: `${lockedFile.path} ${paint.dim(`(sha256: ${shortSha(lockedFile.sha256)})`)}`,
      Status: `${paint.cyan('SUBMITTED')} ${paint.dim('-> queue')}`,
    });

    // ---------------------------------------------------------------------
    // [2/4] Claim — WorkBuddy polls, verifies fingerprints, wins the CAS lease
    // ---------------------------------------------------------------------
    const pollRes = await engine.pollNextTask({ agent_id: 'workbuddy' });
    if (!pollRes.has_task || !pollRes.contract || pollRes.status !== 'CLAIMED') {
      throw new Error(
        `Demo claim failed: expected CLAIMED, got has_task=${pollRes.has_task} status=${pollRes.status ?? 'undefined'}. ` +
          `${pollRes.message ?? ''}`.trim()
      );
    }
    claimToken = pollRes.contract.claim_token ?? '';
    const claimed = pollRes.contract;

    record(2, 'Contract Claimed', {
      Holder: claimed.target_agent,
      Lease: claimToken || paint.yellow('(none)'),
      Status: `${paint.dim('SUBMITTED ->')} ${paint.yellow('CLAIMED')}`,
      Verify: `${paint.green('fingerprints matched')} ${paint.dim('(0 dirty files)')}`,
    });

    // ---------------------------------------------------------------------
    // [3/4] Supervised execution — real child process, heartbeat, schema gate
    // ---------------------------------------------------------------------
    const execResult = await executeTaskAndFulfill(
      engine,
      claimed as unknown as ContractPayload,
      { execFile: handlerPath },
      {
        onEvent: (event: Record<string, unknown>) => {
          if (event.event === 'HEARTBEAT_RENEWED') {
            heartbeatRenewals += 1;
          }
        },
      }
    );

    if (!execResult.ok) {
      throw new Error(`Supervised execution failed: ${execResult.error ?? execResult.status}`);
    }

    // The authoritative delivery lives on the row, not on the fulfill ack.
    const finalState = engine.inspectMeshState({ contract_id: contractId });
    const finalRow = finalState.contracts[0] ?? {};
    status = String(finalRow.status ?? 'UNKNOWN');
    const structured = finalRow.structured_output as Record<string, unknown> | null | undefined;
    if (structured && Array.isArray(structured.issues)) {
      issues = (structured.issues as unknown[]).map((item) => String(item));
    }
    verdict = issues.length > 0 ? 'CHANGES_REQUESTED' : 'PASSED';

    record(3, 'Execution & Schema Check', {
      Handler: `${path.basename(handlerPath)} ${paint.dim('(sandboxed child process)')}`,
      Schema: `${paint.green('passed Ajv validation')}`,
      Heartbeat: heartbeatRenewals > 0
        ? `${paint.green(`${heartbeatRenewals} lease renewal(s)`)}`
        : paint.dim('no renewal needed (short task)'),
      Verdict: verdict === 'PASSED'
        ? paint.green('PASSED')
        : paint.yellow(`CHANGES_REQUESTED ${paint.dim(`(${issues.length} advisory)`)}`),
    });

    // ---------------------------------------------------------------------
    // [4/4] Delivery — second TOCTOU pass then terminal COMPLETED
    // ---------------------------------------------------------------------
    const verifyRes = engine.verifyContract({
      contract_id: contractId,
      agent_id: 'workbuddy',
    });
    dirtyFiles = verifyRes.dirty_files.length;
    if (!verifyRes.valid) {
      throw new Error(
        `Demo TOCTOU re-verification failed: ${verifyRes.dirty_files.length} dirty file(s).`
      );
    }

    if (status !== 'COMPLETED') {
      throw new Error(`Demo expected terminal status COMPLETED, got ${status}.`);
    }

    record(4, 'Contract Completed', {
      TOCTOU: `${paint.green(`fingerprints matched (${dirtyFiles} dirty files)`)}`,
      Final: `${paint.green(paint.bold('COMPLETED'))} ${paint.dim(`(elapsed: ${Date.now() - startedAt}ms)`)}`,
      Findings: issues.length === 0
        ? paint.dim('none')
        : issues.map((item) => paint.dim(item)).join(`\n${' '.repeat(14)}`),
    });

    succeeded = true;
    return {
      ok: true,
      sandbox,
      sandbox_kept: Boolean(options.keep),
      contract_id: contractId,
      claim_token: claimToken,
      status,
      verdict,
      issues,
      dirty_files: dirtyFiles,
      heartbeat_renewals: heartbeatRenewals,
      elapsed_ms: Date.now() - startedAt,
      steps,
      warnings,
    };
  } finally {
    if (engine) {
      try {
        engine.close();
      } catch {
        // Closing is best-effort; the sandbox removal below is the real cleanup contract.
      }
    }

    const retainSandbox = Boolean(options.keep || !succeeded);
    if (retainSandbox) {
      if (options.keep) {
        say('');
        say(`${paint.gray('Sandbox kept at:')} ${sandbox}`);
        say(paint.gray('  Inspect it with: sqlite3 "<sandbox>/demo-mesh.db" ".tables"'));
      }
    } else {
      try {
        removeSandbox(sandbox);
      } catch (err) {
        warnings.push(
          `Sandbox cleanup failed (${err instanceof Error ? err.message : String(err)}); remove "${sandbox}" manually.`
        );
      }
    }

    if (succeeded) {
      say('');
      say(paint.green(paint.bold('  🎉 End-to-end multi-agent handoff verified successfully!')));
      say('');
      say(paint.bold('  Next steps:'));
      say(`    ${paint.gray('•')} Add to your IDE:  ${paint.cyan('npx -y ferrycat')} ${paint.dim('(MCP server entry in mcpServers)')}`);
      say(`    ${paint.gray('•')} Inspect contracts: ${paint.cyan('npx ferrycat inspect --target workbuddy')}`);
      say(`    ${paint.gray('•')} Keep a sandbox:    ${paint.cyan('npx ferrycat demo --keep')}`);
      say(`    ${paint.gray('•')} Full CLI help:     ${paint.cyan('npx ferrycat --help')}`);
    } else {
      say('');
      say(paint.red('  ✖ Demo did not reach a terminal COMPLETED state.'));
      say(paint.gray(`    Sandbox retained for debugging: ${sandbox}`));
    }
  }
}
